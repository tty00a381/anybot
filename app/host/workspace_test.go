func TestUpdatePluginModuleUpdatesMetadata(t *testing.T) {
	dir := t.TempDir()
	if _, err := AddPluginModule(AddPluginOptions{
		Dir:     dir,
		Name:    "weather",
		Module:  "github.com/acme/weather@v1.2.3",
		Replace: "../weather",
		Symbol:  "Module",
	}); err != nil {
		t.Fatal(err)
	}
	updated, workspace, changed, err := UpdatePluginModule(UpdatePluginOptions{
		Dir:          dir,
		Name:         "weather",
		Version:      "v1.3.0",
		Symbol:       "Weather",
		SetVersion:   true,
		SetSymbol:    true,
		ClearReplace: true,
	})
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Fatal("update should report change")
	}
	if updated.Version != "v1.3.0" || updated.Replace != "" || updated.Symbol != "Weather" {
		t.Fatalf("updated = %#v", updated)
	}
	if len(workspace.Plugins) != 1 || workspace.Plugins[0] != updated {
		t.Fatalf("workspace = %#v", workspace)
	}
	manifest := readFile(t, filepath.Join(dir, PluginWorkspaceFile))
	if !strings.Contains(manifest, "version: v1.3.0") ||
		strings.Contains(manifest, "replace:") ||
		!strings.Contains(manifest, "symbol: Weather") {
		t.Fatalf("manifest:\n%s", manifest)
	}
	generated := readFile(t, filepath.Join(dir, generatedPlugins))
	if !strings.Contains(generated, `registry.Register(plugin0.Weather.Factory().WithName("weather"))`) {
		t.Fatalf("generated:\n%s", generated)
	}
}

