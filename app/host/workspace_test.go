func TestGeneratedPluginWorkspaceBuildsLocalPlugin(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	pluginDir := filepath.Join(dir, "weather")
	if err := os.MkdirAll(pluginDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(pluginDir, "go.mod"), []byte(`module example.com/weather

go 1.24

require github.com/tty00a381/anybot v0.0.0
`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(pluginDir, "weather.go"), []byte(`package weather

import (
	"github.com/tty00a381/anybot/core"
	absdk "github.com/tty00a381/anybot/sdk"
)

type Config struct {
	Command string `+"`yaml:\"command\"`"+`
}

var Module = absdk.Define(
	core.Manifest{Name: "weather", Version: "1.0.0", Description: "天气插件"},
	Config{Command: "weather"},
	func(ctx *absdk.Context, cfg Config) error {
		return nil
	},
)
`), 0o644); err != nil {
		t.Fatal(err)
	}

	botDir := filepath.Join(dir, "bot")
	if _, err := AddPluginModule(AddPluginOptions{Dir: botDir, Name: "daily_weather", Module: "example.com/weather"}); err != nil {
		t.Fatal(err)
	}
	runGo(t, botDir, "mod", "edit", "-replace", "github.com/tty00a381/anybot="+root)
	runGo(t, botDir, "mod", "edit", "-replace", "example.com/weather="+pluginDir)
	runGo(t, botDir, "mod", "tidy")
	runGo(t, botDir, "build", "-o", "anybot-bot", ".")
	if err := os.WriteFile(filepath.Join(botDir, "anybot.yaml"), []byte(`plugin_config_dir: plugins.d
plugins: {}
`), 0o644); err != nil {
		t.Fatal(err)
	}
	out := runCommand(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "enable", "daily_weather")
	if !strings.Contains(out, "插件已启用：daily_weather") ||
		!strings.Contains(out, "默认配置已同步：1 项更新") {
		t.Fatalf("plugin enable:\n%s", out)
	}
	pluginConfig := readFile(t, filepath.Join(botDir, "plugins.d", "daily_weather.yaml"))
	if !strings.Contains(pluginConfig, "enabled: true") ||
		!strings.Contains(pluginConfig, "command: weather") {
		t.Fatalf("plugin config:\n%s", pluginConfig)
	}
	out = runCommand(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "status")
	if !strings.Contains(out, "daily_weather\t外部\t是\t是\t是\t1.0.0\texample.com/weather") {
		t.Fatalf("plugin status:\n%s", out)
	}
	out = runCommand(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "check")
	if !strings.Contains(out, "daily_weather\t外部\t可用\t-") {
		t.Fatalf("plugin check:\n%s", out)
	}
	out = runCommand(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "inspect", "daily_weather")
	if !strings.Contains(out, "名称：daily_weather") ||
		!strings.Contains(out, "默认配置：") ||
		!strings.Contains(out, "command: weather") {
		t.Fatalf("plugin inspect:\n%s", out)
	}
	out = runCommand(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "config", "daily_weather", "command=forecast")
	if !strings.Contains(out, "插件配置已更新：daily_weather") {
		t.Fatalf("plugin config:\n%s", out)
	}
	pluginConfig = readFile(t, filepath.Join(botDir, "plugins.d", "daily_weather.yaml"))
	if !strings.Contains(pluginConfig, "command: forecast") {
		t.Fatalf("plugin config:\n%s", pluginConfig)
	}
	out = runCommand(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "disable", "daily_weather")
	if !strings.Contains(out, "插件已禁用：daily_weather") {
		t.Fatalf("plugin disable:\n%s", out)
	}
	pluginConfig = readFile(t, filepath.Join(botDir, "plugins.d", "daily_weather.yaml"))
	if !strings.Contains(pluginConfig, "enabled: false") ||
		!strings.Contains(pluginConfig, "command: forecast") {
		t.Fatalf("plugin config:\n%s", pluginConfig)
	}
	out, err = runCommandErr(t, botDir, filepath.Join(botDir, "anybot-bot"), "plugin", "config", "weathre", "command=bad")
	if err == nil {
		t.Fatal("unknown plugin config should fail")
	}
	if !strings.Contains(out, `未知插件 "weathre"`) {
		t.Fatalf("plugin config error:\n%s", out)
	}
	if _, err := os.Stat(filepath.Join(botDir, "plugins.d", "weathre.yaml")); !os.IsNotExist(err) {
		t.Fatalf("unknown plugin config should not be created: %v", err)
	}
}

func runGo(t *testing.T, dir string, args ...string) {
	t.Helper()
	runCommand(t, dir, "go", args...)
}

func runCommand(t *testing.T, dir, name string, args ...string) string {
	t.Helper()
	out, err := runCommandErr(t, dir, name, args...)
	if err != nil {
		t.Fatalf("%s %s failed: %v\n%s", name, strings.Join(args, " "), err, out)
	}
	return out
}

func runCommandErr(t *testing.T, dir, name string, args ...string) (string, error) {
	t.Helper()
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}
