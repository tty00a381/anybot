func TestAddPluginModuleGeneratesWorkspace(t *testing.T) {
	dir := t.TempDir()
	workspace, err := AddPluginModule(AddPluginOptions{
		Dir:    dir,
		Module: "github.com/acme/anybot-weather",
		Symbol: "Weather",
	})
	if err != nil {
		t.Fatal(err)
	}
	if workspace.Module != "anybot.local/bot" || len(workspace.Plugins) != 1 {
		t.Fatalf("workspace = %#v", workspace)
	}
	if workspace.Plugins[0].Name != "anybot_weather" {
		t.Fatalf("plugin name = %q", workspace.Plugins[0].Name)
	}
	manifest := readFile(t, filepath.Join(dir, PluginWorkspaceFile))
	if !strings.Contains(manifest, "github.com/acme/anybot-weather") {
		t.Fatalf("manifest:\n%s", manifest)
	}
	generated := readFile(t, filepath.Join(dir, generatedPlugins))
	if !strings.Contains(generated, "Code generated by anybot") ||
		!strings.Contains(generated, `plugin0 "github.com/acme/anybot-weather"`) ||
		!strings.Contains(generated, `plugin0.Weather.Factory().WithName("anybot_weather")`) {
		t.Fatalf("generated:\n%s", generated)
	}
	mainGo := readFile(t, filepath.Join(dir, generatedMain))
	if !strings.Contains(mainGo, "Code generated by anybot") ||
		!strings.Contains(mainGo, "registerExternalPlugins(registry)") ||
		!strings.Contains(mainGo, `os.Args[1] == "plugin"`) ||
		!strings.Contains(mainGo, "host.SyncPluginConfigEntriesForWorkspace") ||
		!strings.Contains(mainGo, "host.WritePluginConfigSyncSummary") ||
		!strings.Contains(mainGo, "host.WritePluginStatusTable") ||
		!strings.Contains(mainGo, "host.WritePluginInspect") ||
		!strings.Contains(mainGo, "host.EnsureKnownPluginTarget") ||
		!strings.Contains(mainGo, "host.SetPluginEnabled") ||
		!strings.Contains(mainGo, "host.SyncPluginConfigEntry") ||
		!strings.Contains(mainGo, "host.WritePluginConfigCheckTable") {
		t.Fatalf("main.go:\n%s", mainGo)
	}
	goMod := readFile(t, filepath.Join(dir, "go.mod"))
	if !strings.Contains(goMod, "module anybot.local/bot") {
		t.Fatalf("go.mod:\n%s", goMod)
	}
}

