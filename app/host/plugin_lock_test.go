func TestAddPluginModuleGeneratesLockAndHost(t *testing.T) {
	dir := t.TempDir()
	lock, err := AddPluginModule(AddPluginOptions{
		Dir:    dir,
		Module: "github.com/acme/anybot-weather",
		Symbol: "Weather",
	})
	if err != nil {
		t.Fatal(err)
	}
	if lock.Module != "anybot.local/bot" || len(lock.Plugins) != 1 {
		t.Fatalf("lock = %#v", lock)
	}
	if lock.Plugins[0].Name != "anybot_weather" {
		t.Fatalf("plugin name = %q", lock.Plugins[0].Name)
	}
	wantID := DefaultPluginInstanceID("github.com/acme/anybot-weather", "Weather")
	if lock.Plugins[0].ID != wantID {
		t.Fatalf("plugin id = %q, want %q", lock.Plugins[0].ID, wantID)
	}
	lockText := readFile(t, filepath.Join(dir, PluginLockFile))
	if !strings.Contains(lockText, "github.com/acme/anybot-weather") || !strings.Contains(lockText, "id: "+wantID) {
		t.Fatalf("lockText:\n%s", lockText)
	}
	generated := readFile(t, filepath.Join(dir, generatedPlugins))
	if !strings.Contains(generated, "Code generated by anybot") ||
		!strings.Contains(generated, `plugin0 "github.com/acme/anybot-weather"`) ||
		!strings.Contains(generated, `plugin0.Weather.Factory().WithName("anybot_weather").WithInstanceID("`+wantID+`")`) {
		t.Fatalf("generated:\n%s", generated)
	}
	mainGo := readFile(t, filepath.Join(dir, generatedMain))
	if !strings.Contains(mainGo, "Code generated by anybot") ||
		!strings.Contains(mainGo, "registerExternalPlugins(registry)") ||
		!strings.Contains(mainGo, `os.Args[1] == "plugin"`) ||
		!strings.Contains(mainGo, "host.RunPluginCommand") ||
		!strings.Contains(mainGo, "Args:       os.Args[2:]") ||
		!strings.Contains(mainGo, "host.NewApp") {
		t.Fatalf("main.go:\n%s", mainGo)
	}
	if strings.Contains(mainGo, "host.SyncPluginConfigEntry") ||
		strings.Contains(mainGo, "host.WritePluginStatusTable") ||
		strings.Contains(mainGo, "host.EnsureKnownPluginTarget") {
		t.Fatalf("generated main should delegate plugin command handling:\n%s", mainGo)
	}
	goMod := readFile(t, filepath.Join(dir, "go.mod"))
	if !strings.Contains(goMod, "module anybot.local/bot") {
		t.Fatalf("go.mod:\n%s", goMod)
	}
}

