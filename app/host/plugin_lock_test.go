func TestUpdatePluginModuleUpdatesMetadata(t *testing.T) {
	dir := t.TempDir()
	if _, err := AddPluginModule(AddPluginOptions{
		Dir:     dir,
		Name:    "weather",
		Module:  "github.com/acme/weather@v1.2.3",
		Replace: "../weather",
		Symbol:  "Module",
	}); err != nil {
		t.Fatal(err)
	}
	updated, lock, changed, err := UpdatePluginModule(UpdatePluginOptions{
		Dir:          dir,
		Name:         "weather",
		Version:      "v1.3.0",
		Symbol:       "Weather",
		SetVersion:   true,
		SetSymbol:    true,
		ClearReplace: true,
	})
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Fatal("update should report change")
	}
	wantID := DefaultPluginInstanceID("github.com/acme/weather", "Module")
	if updated.Version != "v1.3.0" || updated.Replace != "" || updated.Symbol != "Weather" || updated.ID != wantID {
		t.Fatalf("updated = %#v", updated)
	}
	if len(lock.Plugins) != 1 || lock.Plugins[0] != updated {
		t.Fatalf("lock = %#v", lock)
	}
	lockText := readFile(t, filepath.Join(dir, PluginLockFile))
	if !strings.Contains(lockText, "version: v1.3.0") ||
		strings.Contains(lockText, "replace:") ||
		!strings.Contains(lockText, "symbol: Weather") {
		t.Fatalf("lockText:\n%s", lockText)
	}
	generated := readFile(t, filepath.Join(dir, generatedPlugins))
	if !strings.Contains(generated, `registry.Register(plugin0.Weather.Factory().WithName("weather").WithInstanceID("`+wantID+`"))`) {
		t.Fatalf("generated:\n%s", generated)
	}
}

